#!/usr/bin/env node
/* Convert the pinned upstream data to native tables. No browser is needed on
 * the device. Run: node tools/build_aora_face.cjs */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const upstream = path.join(root, 'third_party/aora-bot/emotion-ball/js');
const context = vm.createContext({ window: {} });
for (const name of ['rings', 'emotions']) {
  vm.runInContext(fs.readFileSync(path.join(upstream, name + '.js'), 'utf8'), context);
}
const { EB_RINGS: rings, EMOTION_SEED: emotions } = context.window;
const bodyKeys = ['x', 'y', 'scale', 'rotate', 'breathe', 'ribbons', 'confetti', 'zzz', 'orbit'];
const eyeKeys = ['x', 'y', 'scaleX', 'scaleY', 'rotate', 'open', 'lookX', 'lookY'];
const defaults = {
  body: { x: 0, y: 0, scale: 1, rotate: 0, breathe: 0.01, color: '#F3F0EA', ribbons: 0, confetti: 0, zzz: 0, orbit: 0 },
  left: { x: 0, y: 0, scaleX: 1, scaleY: 1, rotate: 0, open: 1, color: '#1A1A1A', lookX: 0, lookY: 0 },
  right: { x: 0, y: 0, scaleX: 1, scaleY: 1, rotate: 0, open: 1, color: '#1A1A1A', lookX: 0, lookY: 0 }
};
function pose(spec, base = defaults) {
  return {
    body: { ...base.body, ...spec.body },
    left: { ...base.left, ...spec.eyes?.both, ...spec.eyes?.left },
    right: { ...base.right, ...spec.eyes?.both, ...spec.eyes?.right }
  };
}
function number(n) {
  if (!Number.isFinite(n)) throw new Error('Non-finite source number');
  return Number.isInteger(n) ? n + '.0f' : n + 'f';
}
function color(value) {
  if (!/^#[0-9A-Fa-f]{6}$/.test(value)) throw new Error('Invalid source color');
  return '0x' + value.slice(1).toUpperCase();
}
function cPose(p) {
  return '{ {' + [...bodyKeys.map(k => p.body[k]), ...eyeKeys.map(k => p.left[k]), ...eyeKeys.map(k => p.right[k])].map(number).join(', ') + '}, {' + [p.body.color, p.left.color, p.right.color].map(color).join(', ') + '} }';
}
function points(ring) { return '{' + ring.map(p => '{' + p.map(number).join(',') + '}').join(',') + '}'; }
const lines = [
  '/* Generated by tools/build_aora_face.cjs. Do not edit.',
  ' * Source: sam70361/aora-bot e3b6148c818da4a8e1966f2bc89cdb3cee473b73.',
  ' * Copyright (c) 2026 sam70361; see third_party/aora-bot/LICENSE and NOTICE.md. */',
  'static const lv_fpoint_t aora_body[96] = ' + points(rings.SHAPES.blob.ring) + ';',
  'static const lv_fpoint_t aora_eyes[25][2][48] = {'
];
for (const pair of rings.EXPRESSIONS) lines.push('    {' + pair.map(points).join(',') + '},');
lines.push('};');
const types = { sine: 'AORA_SINE', pulse: 'AORA_PULSE', jitter: 'AORA_JITTER', scan: 'AORA_SCAN', glance: 'AORA_GLANCE', blink: 'AORA_BLINK' };
const targets = { body: 0, eyes: 1, left: 2, right: 3 };
emotions.forEach((e, i) => {
  if (e.pool.length > 8 || e.pool.some(p => p < 0 || p >= 25)) throw new Error('Invalid eye pool');
  if (e.anims?.length) {
    lines.push('static const aora_anim_t aora_anims_' + i + '[] = {');
    for (const a of e.anims) {
      const prop = a.target === 'body' ? bodyKeys.indexOf(a.prop) : a.prop === 'scale' ? 8 : eyeKeys.indexOf(a.prop);
      if (prop < 0 || targets[a.target] === undefined || !types[a.type]) throw new Error('Unsupported animation');
      lines.push('    {' + [targets[a.target], prop, types[a.type], number(a.amp || 0), a.period || a.interval || 2000, number(a.phase || 0), a.phaseMs || 0, number(a.speed || 8), a.decay || 0, a.dur || 200, number(a.depth ?? 1)].join(', ') + '},');
    }
    lines.push('};');
  }
  if (e.sequence) {
    lines.push('static const aora_frame_t aora_frames_' + i + '[] = {');
    for (const frame of e.sequence.frames) lines.push('    {' + frame.at + ', ' + cPose(pose(frame, pose(e))) + '},');
    lines.push('};');
  }
});
lines.push('static const aora_emotion_t aora_emotions[] = {');
emotions.forEach((e, i) => {
  const blink = e.blinkMs === null ? [0, 0] : e.blinkMs || [6000, 14000];
  const settle = !e.sequence || e.sequence.settle === 'base' ? 0 : e.sequence.settle === 'hold' ? 1 : 2;
  const next = settle === 2 ? emotions.findIndex(n => n.id === e.sequence.settle.next) : 0;
  lines.push('    {"' + e.id + '", ' + (e.transition ?? 500) + ', {' + e.pool.join(',') + '}, ' + e.pool.length + ', {' + e.poolMs.join(',') + '}, {' + blink.join(',') + '}, ' + number(e.openness ?? 1) + ', ' + Number(!!e.antics) + ', ' + Number(e.gaze !== false) + ',');
  lines.push('     ' + cPose(pose(e)) + ', ' + (e.anims?.length ? 'aora_anims_' + i : 'NULL') + ', ' + (e.anims?.length || 0) + ', ' + (e.sequence ? 'aora_frames_' + i : 'NULL') + ', ' + (e.sequence?.frames.length || 0) + ', ' + settle + ', ' + next + '},');
});
lines.push('};', '');
fs.writeFileSync(path.join(root, 'app/ai_face_data.h'), lines.join('\n'));
console.log('Generated ball geometry, 25 eye pairs and ' + emotions.length + ' expressions.');
